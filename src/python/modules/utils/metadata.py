def attach_column_descriptions(df: DataFrame) -> DataFrame:
    """Attach Unity Catalog column comment metadata in a single `.select()` projection."""
    return df.select(
        *[
            F.col(col_name).alias(
                col_name,
                metadata={"comment": ML_COLUMN_DESCRIPTIONS.get(col_name, f"Governed ML attribute {col_name}.")},
            )
            for col_name in df.columns
        ]
    )


def build_schema_provisioning_ddls(cfg: MLProjectConfig) -> tuple[str, ...]:
    """Build SQL DDL statements creating and documenting the ML Unity Catalog schemas."""
    statements: list[str] = []
    for schema_name in (cfg.feature_schema, cfg.model_schema, cfg.predictions_schema, cfg.trace_schema):
        desc = ML_SCHEMA_DESCRIPTIONS.get(schema_name, f"Governed ML schema {schema_name}.").replace("'", "\\'")
        statements.append(f"CREATE SCHEMA IF NOT EXISTS `{cfg.catalog}`.`{schema_name}` COMMENT '{desc}'")
    return tuple(statements)
